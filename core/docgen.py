"""ETL documentation in Markdown with a Mermaid lineage diagram (BRD FR-19). No LLM, deterministic.

`script_doc(script, title)` turns a ScriptAnalysis (one or many statements, procedures included) into a
Markdown document: summary, a Mermaid flowchart of tables -> steps -> tables, and one section per
statement with its SQL, plain-English steps, problems and column lineage.
"""
from __future__ import annotations

import re

from core.sql_analyzer import DIALECTS, Analysis
from core.sql_script import ScriptAnalysis, StatementResult

SEVERITY_WORDS = {"high": "Likely bug", "medium": "Slow or fragile", "low": "Worth a look"}


def _node_id(prefix: str, name: str, ids: dict[str, str]) -> str:
    key = f"{prefix}:{name.lower()}"
    if key not in ids:
        ids[key] = f"{prefix}{len(ids)}"
    return ids[key]


def _label(text: str) -> str:
    """Mermaid label: quoted, with characters that break the syntax replaced."""
    clean = re.sub(r'["<>{}|`]', "'", text)
    return '"' + " ".join(clean.split())[:60] + '"'


def _md(text: str) -> str:
    """Escape table-breaking characters for a Markdown table cell."""
    return " ".join(str(text).replace("|", "\\|").split())


def mermaid(script: ScriptAnalysis) -> str:
    """Flowchart: source tables -> statement -> written tables. Statements that write nothing feed 'result'."""
    ids: dict[str, str] = {}
    lines = ["flowchart LR"]
    for s in script.all_statements:
        a = s.analysis
        if not a.tables and not a.target:
            continue
        step = _node_id("s", str(s.index), ids)
        name = f"{s.index}. {a.statement}" + (f" in {s.procedure}" if s.procedure else "")
        lines.append(f"  {step}[{_label(name)}]")
        for t in a.tables:
            lines.append(f"  {_node_id('t', t, ids)}[({_label(t)})] --> {step}")
        if a.target:
            lines.append(f"  {step} --> {_node_id('t', a.target, ids)}[({_label(a.target)})]")
    if len(lines) == 1:
        lines.append('  none["No tables are read or written"]')
    return "\n".join(lines)


def _statement_section(s: StatementResult, dialect: str) -> list[str]:
    a: Analysis = s.analysis
    where = f" (in procedure `{s.procedure}`)" if s.procedure else ""
    out = [f"### {s.index}. {a.statement}{where}, line {s.line}", "", f"```sql\n{s.sql.strip()}\n```", ""]
    if a.explanation:
        out += ["**What it does**", ""] + [f"{n}. {step}" for n, step in enumerate(a.explanation, 1)] + [""]
    if a.tables or a.target:
        out += [f"- Reads: {', '.join(f'`{t}`' for t in a.tables) or '-'}",
                f"- Writes: {f'`{a.target}`' if a.target else '-'}", ""]
    if a.issues:
        out += ["**Possible problems**", ""]
        for i in a.issues:
            out.append(f"- **{SEVERITY_WORDS.get(i.severity, i.severity)}: {i.title}.** {i.why} "
                       f"*How to fix:* {i.fix}")
        out.append("")
    else:
        out += ["No common problems found.", ""]
    if a.lineage:
        out += ["**Where each column comes from**", "", "| Result column | Comes from | How it is made |",
                "|---|---|---|"]
        for l in a.lineage:
            src = ", ".join(l.sources) if l.sources else "(fixed value)"
            out.append(f"| {_md(l.output)} | {_md(src)} | `{_md(l.expression)}` |")
        out.append("")
    return out


def script_doc(script: ScriptAnalysis, title: str = "SQL documentation") -> str:
    stmts = script.all_statements
    problems = sum(len(s.analysis.issues) for s in stmts)
    lines = [f"# {title}", "",
             f"Generated by DE Bro Code SQL Autopsy. Database: {DIALECTS.get(script.dialect, script.dialect)}.", "",
             "## Summary", "",
             f"- Statements explained: {len(stmts)}",
             f"- Stored procedures / functions: {len(script.procedures)}",
             f"- Tables read: {', '.join(f'`{t}`' for t in script.tables_read) or '-'}",
             f"- Tables written: {', '.join(f'`{t}`' for t in script.tables_written) or '-'}",
             f"- Possible problems: {problems}",
             f"- Syntax problems: {len(script.syntax_problems)}", "",
             "## Data flow", "", "```mermaid", mermaid(script), "```", ""]
    if script.procedures:
        lines += ["## Procedures", "", "| Name | Kind | Parameters | Line | Statements | Not analysed |",
                  "|---|---|---|---|---|---|"]
        for p in script.procedures:
            lines.append(f"| `{_md(p.name)}` | {p.kind.lower()} | {_md(p.params) or '-'} | {p.line} | "
                         f"{len(p.statements)} | {len(p.not_analysed)} |")
        lines.append("")
    if script.syntax_problems:
        lines += ["## Syntax problems", ""] + [
            f"- Line {u.line}{f' (in {u.procedure})' if u.procedure else ''}: {u.message}"
            for u in script.syntax_problems] + [""]
    lines += ["## Statements", ""]
    for s in stmts:
        lines += _statement_section(s, script.dialect)
    skipped = [u for u in script.all_unreadable if u not in script.syntax_problems]
    if skipped:
        lines += ["## Not analysed", "", "| Line | In | Text | Why |", "|---|---|---|---|"]
        for u in skipped:
            lines.append(f"| {u.line} | {_md(u.procedure or '-')} | `{_md(u.sql)[:70]}` | {_md(u.message)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
